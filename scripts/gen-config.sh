#!/bin/sh
# Generate the firmware config header from the settings exported by
# GNUmakefile, with the Let's Encrypt root certificates embedded. The header
# is only replaced when its content changes, so unchanged settings don't
# trigger a rebuild.
#
# Usage: gen-config.sh OUTPUT_HEADER CA_PEM_FILE
set -eu

out=$1
pem=$2

die() {
    echo "error: $*" >&2
    exit 1
}

for v in WIFI_SSID GPS_LAT GPS_LON WIGLE_API_NAME WIGLE_API_TOKEN; do
    eval "[ -n \"\${$v:-}\" ]" || die "$v is not set; run 'make config'."
done

# check VAR REGEX
check() {
    eval "val=\${$1:-}"
    printf '%s\n' "$val" | grep -Eq "$2" || die "invalid $1: '$val'"
}
check GPS_LAT '^-?[0-9]+(\.[0-9]+)?$'
check GPS_LON '^-?[0-9]+(\.[0-9]+)?$'
check GPS_ALT '^-?[0-9]+$'
check GPS_ACC '^[0-9]+(\.[0-9]+)?$'
check WIFI_COUNTRY '^[A-Z]{2}$'
check NTP_SERVER '^[A-Za-z0-9.-]+$'
check SCAN_INTERVAL '^[1-9][0-9]{0,3}$'
check UPLOAD_INTERVAL '^[1-9][0-9]{1,5}$'

# PICO_PROXY: socks5://[user:pass@]host:port
proxy_host='' proxy_port=0 proxy_user='' proxy_pass=''
if [ -n "${PICO_PROXY:-}" ]; then
    case $PICO_PROXY in
        socks5://* | socks5h://*) rest=${PICO_PROXY#*://} ;;
        *) die "PICO_PROXY must look like socks5://[user:pass@]host:port" ;;
    esac
    rest=${rest%/}
    case $rest in
        *@*)
            auth=${rest%@*}
            rest=${rest##*@}
            proxy_user=${auth%%:*}
            case $auth in *:*) proxy_pass=${auth#*:} ;; esac
            ;;
    esac
    proxy_host=${rest%:*}
    proxy_port=${rest##*:}
    if [ -z "$proxy_host" ] || [ "$proxy_host" = "$rest" ] ||
        ! printf '%s\n' "$proxy_port" | grep -Eq '^[1-9][0-9]{0,4}$' ||
        [ "$proxy_port" -gt 65535 ]; then
        die "invalid PICO_PROXY: '$PICO_PROXY'"
    fi
fi

# def NAME VALUE (printf, since echo in some shells eats backslashes)
def() {
    printf '#define %-17s %s\n' "$1" "$2"
}

# C string literal.
cstr() {
    printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
}

c1=$(printf '%s' "$WIFI_COUNTRY" | cut -c1)
c2=$(printf '%s' "$WIFI_COUNTRY" | cut -c2)

mkdir -p "$(dirname "$out")"
umask 077
{
    echo '// Generated by scripts/gen-config.sh; edit GNUmakefile.local instead.'
    echo '#pragma once'
    echo
    def WIFI_SSID "$(cstr "$WIFI_SSID")"
    def WIFI_PASSWORD "$(cstr "${WIFI_PASSWORD:-}")"
    def WIFI_COUNTRY "CYW43_COUNTRY('$c1', '$c2', 0)"
    def GPS_LAT "\"$GPS_LAT\""
    def GPS_LON "\"$GPS_LON\""
    def GPS_ALT "\"$GPS_ALT\""
    def GPS_ACC "\"$GPS_ACC\""
    def WIGLE_API_NAME "$(cstr "$WIGLE_API_NAME")"
    def WIGLE_API_TOKEN "$(cstr "$WIGLE_API_TOKEN")"
    def PROXY_HOST "$(cstr "$proxy_host")"
    def PROXY_PORT "$proxy_port"
    def PROXY_USER "$(cstr "$proxy_user")"
    def PROXY_PASS "$(cstr "$proxy_pass")"
    def NTP_SERVER "\"$NTP_SERVER\""
    def SCAN_INTERVAL_S "$SCAN_INTERVAL"
    def UPLOAD_INTERVAL_S "$UPLOAD_INTERVAL"
    echo
    echo "// Let's Encrypt root certificates (PEM)."
    echo '#define CA_PEM \'
    tr -d '\r' < "$pem" | sed -e 's/^/    "/' -e 's/$/\\n" \\/'
    echo '    ""'
} > "$out.tmp"

if cmp -s "$out.tmp" "$out"; then
    rm -f "$out.tmp"
else
    mv "$out.tmp" "$out"
fi
